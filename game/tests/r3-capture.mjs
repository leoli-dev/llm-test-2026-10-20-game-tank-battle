import { chromium } from 'playwright';
const EXE = process.env.CHROMIUM_PATH || undefined;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await chromium.launch({ executablePath: EXE, headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on('pageerror', (e) => errors.push('' + e));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto((process.env.BASE_URL || 'http://127.0.0.1:5179/'));
await sleep(800);
await page.screenshot({ path: 'tests/evidence/r3-01-menu.png' });
await page.click('#btnStart');
await sleep(2500);
await page.screenshot({ path: 'tests/evidence/r3-02-fullmap.png' });
const v = await page.evaluate(() => window.__game.validateLevelNow());
console.log('in-game validateLevel:', JSON.stringify(v));
console.log('errors:', errors.length, errors[0] || '');
await browser.close();
process.exit(errors.length ? 1 : 0);
